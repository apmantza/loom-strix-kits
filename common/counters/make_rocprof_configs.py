#!/usr/bin/env python3
"""Generate common/counters/rocprof-compute-<arch>/ : AMD rocprofiler-compute's analysis configs for the chip (MIT, AMD), with the
peaks this machine reaches taken from the device file (common/devices/<gfx>.json, one profile), so `rocprof-compute analyze
--config-dir` reports % of peak against the clock and bandwidth the chip holds, not its boost clock and a wrong fabric figure.
Changes against AMD's copy (metric ids, names and value expressions otherwise unchanged):
  - every $max_sclk (2900 MHz: boost, never held inside the 85 W cap) -> the profile's clock_ghz in MHz (compute and cache peaks);
  - GL2-Fabric Read / Write peak ($max_mclk x 4 x channels x 4 B = 128 GB/s on gfx1151, half the LPDDR5X-8000 256-bit bus) ->
    the profile's bw_practical_gbs (the measured streaming read);
  - SPI panel 6.2 'Compute Wave Dispatches' / 'Wave Dispatch Rate' -> marked unsupported (SPI_CSN_WAVE reads 0 on gfx1151).
Fails closed: an AMD file whose text no longer has the expected expressions stops the run (regenerate by hand after reading it).
Regenerate whenever the device file changes; common/test_rocprof_configs.py fails when the copy no longer matches it.
usage: make_rocprof_configs.py [--amd DIR] [--device JSON] [--profile NAME] [--out DIR]
       (--amd default: $ROCM_SDK/../_rocm_profiler/libexec/rocprofiler-compute/rocprof_compute_soc/analysis_configs/gfx115x)"""
import argparse, glob, json, os, re, sys

H = os.path.dirname(os.path.abspath(__file__))
FABRIC = "$max_mclk * 4 * $num_memory_channels * 4 * 1e6"
UNSUP = "None"
SPI_ROWS = ("Compute Wave Dispatches", "Wave Dispatch Rate")


def amd_dir():
    sdk = os.environ.get("ROCM_SDK")
    if not sdk:
        env = os.environ.get("LSK_ENV", os.path.expanduser("~/.config/loom-strix-kits/env"))
        if os.path.exists(env):
            m = re.search(r"^ROCM_SDK=(\S+)", open(env).read(), re.M)
            sdk = m and m.group(1)
    return sdk and os.path.join(os.path.dirname(sdk), "_rocm_profiler/libexec/rocprofiler-compute/rocprof_compute_soc/analysis_configs/gfx115x")


def peaks(device, profile=None):
    d = json.load(open(device))
    name = profile or d["default_profile"]
    p = d["profiles"][name]
    return name, int(round(p["clock_ghz"] * 1000)), float(p["bw_practical_gbs"])


def transform(fname, text, mhz, gbs, prof):
    """the edited text of one AMD file; raises ValueError when an expected expression is missing"""
    if fname.startswith("0200_"):
        n = text.count(FABRIC)
        if n != 2:
            raise ValueError(f"{fname}: {n} fabric peak expressions, expected 2")
        text = text.replace(FABRIC, f"{gbs:g}e9")
        text = re.sub(r"^(\s*)# peak: LPDDR5X - \$max_mclk.*$",
                      rf"\1# peak: device file profile {prof}: {gbs:g} GB/s measured streaming read (AMD's max_mclk x 4 x channels x 4 B gave 128 GB/s)",
                      text, flags=re.M)
        text = text.replace("Requires $max_mclk populated in sysinfo (max MEM clock from amd-smi).",
                            f"Peak: {gbs:g} GB/s, the measured streaming read of the device file's {prof} profile.")
        if text.count("$max_sclk") != 7:
            raise ValueError(f"{fname}: {text.count('$max_sclk')} $max_sclk, expected 7")
    text = text.replace("$max_sclk", str(mhz))
    if fname.startswith("0600_"):
        for row in SPI_ROWS:
            pat = re.compile(rf"(\n        {re.escape(row)}:\n)((?:          (?:avg|min|max|unit):.*\n)+)")
            if not pat.search(text):
                raise ValueError(f"{fname}: row {row!r} not found")
            text = pat.sub(lambda m: m.group(1) + f"          avg: {UNSUP}\n          min: {UNSUP}\n          max: {UNSUP}\n"
                           "          unit: unsupported on gfx1151 (SPI_CSN_WAVE reads 0; SQ_WAVES counts waves)\n", text)
        if "SPI_CSN_WAVE)" in text or "SPI_CSN_WAVE /" in text:
            raise ValueError(f"{fname}: SPI_CSN_WAVE still in an expression")
    if re.search(r"\$max_(sclk|mclk)", text):
        raise ValueError(f"{fname}: $max_sclk / $max_mclk left")
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--amd", default=amd_dir())
    ap.add_argument("--device", default=os.path.join(H, "..", "devices", "gfx1151.json"))
    ap.add_argument("--profile")
    ap.add_argument("--out", default=os.path.join(H, "rocprof-compute-gfx115x"))
    a = ap.parse_args()
    src = sorted(glob.glob(os.path.join(a.amd or "", "*.yaml")))
    if not src:
        sys.exit(f"make_rocprof_configs: no AMD configs under {a.amd!r} (set ROCM_SDK or --amd)")
    ver_f = os.path.join(a.amd, "..", "..", "..", "VERSION")
    ver = open(ver_f).read().strip() if os.path.exists(ver_f) else "unknown"
    prof, mhz, gbs = peaks(a.device, a.profile)
    os.makedirs(a.out, exist_ok=True)
    head = (f"# Generated by common/counters/make_rocprof_configs.py: do not edit, regenerate. Source: AMD rocprofiler-compute {ver}\n"
            f"# analysis_configs/gfx115x, Copyright (c) Advanced Micro Devices, Inc., SPDX-License-Identifier: MIT (LICENSE-AMD.md).\n"
            f"# Peaks from {os.path.basename(a.device)} profile {prof}: clock {mhz} MHz (was max_sclk), fabric {gbs:g} GB/s.\n")
    for f in src:
        n = os.path.basename(f)
        try:
            t = transform(n, open(f).read(), mhz, gbs, prof)
        except ValueError as e:
            sys.exit(f"make_rocprof_configs: {e}: AMD's file changed; read it and update this script")
        open(os.path.join(a.out, n), "w").write(head + t)
    print(f"make_rocprof_configs: {len(src)} files -> {a.out} (profile {prof}: {mhz} MHz, {gbs:g} GB/s; rocprofiler-compute {ver})")


if __name__ == "__main__":
    main()
